"""PostgreSQL support (w408): the same SQL on both databases.

The whole test suite also runs on PostgreSQL when SGXRAY_TEST_PG is set (see conftest.py).
"""

import pytest

import db


def test_question_marks_become_psycopg_placeholders_outside_quotes():
    assert db._placeholders("SELECT * FROM t WHERE a = ? AND b = '?'") == "SELECT * FROM t WHERE a = %s AND b = '?'"
    assert db._placeholders("SELECT '50%' WHERE x LIKE ?") == "SELECT '50%%' WHERE x LIKE %s"


@pytest.mark.skipif(db.psycopg is None, reason="psycopg not installed")
def test_a_database_on_another_computer_is_always_encrypted():
    assert db._tls("postgresql://u:p@ep-x.ap-southeast-1.aws.neon.tech/db") == {"sslmode": "require"}
    assert db._tls("postgresql://u:p@db.example.com/db?sslmode=verify-full") == {}     # a stricter choice is kept
    assert db._tls("postgresql://u:p@127.0.0.1:54329/db") == {}                         # this computer: no TLS needed


def test_each_database_gets_its_own_words_in_the_schema():
    pg = db.schema_sql("postgres")
    assert "GENERATED BY DEFAULT AS IDENTITY" in pg and "DOUBLE PRECISION" in pg
    assert "strftime" not in pg and "INTEGER PRIMARY KEY" not in pg and " REAL " not in pg
    lite = db.schema_sql("sqlite")
    assert "INTEGER PRIMARY KEY" in lite and "strftime" in lite and "{" not in lite


def test_no_sqlite_only_sql_is_left_in_the_app():
    from pathlib import Path
    src = Path(__file__).resolve().parent.parent / "src"
    for f in list(src.glob("*.py")) + [src.parent / "app.py"]:
        text = f.read_text(encoding="utf-8")
        for word in ("INSERT OR IGNORE", "INSERT OR REPLACE", "GROUP_CONCAT", "TOTAL(", "lastrowid", "total_changes"):
            assert word not in text, (f.name, word)

